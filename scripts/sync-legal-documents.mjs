import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import {
  legalLanguages, readLegalSource, root, validateLegalTranslation, webLegalLanguages,
} from './legal-document-utils.mjs';

const source = readLegalSource();
const bundles = Object.fromEntries(legalLanguages.map(language => {
  const bundle = JSON.parse(readFileSync(new URL(`docs/legal-locales/${language}.json`, root), 'utf8'));
  validateLegalTranslation(bundle, source, language);
  return [language, bundle];
}));
const write = (file, value) => writeFileSync(new URL(file, root), value);
const json = value => JSON.stringify(value, null, 2) + '\n';
for (const target of ['src/features/legal/documents.generated.json', 'web/src/data/legal-documents.generated.json']) {
  write(target, json(source.documents));
}
for (const directory of ['src/features/legal/locales/', 'web/src/data/legal-locales/']) {
  mkdirSync(new URL(directory, root), { recursive: true });
}
for (const [language, bundle] of Object.entries(bundles)) {
  write(`src/features/legal/locales/${language}.json`, json(bundle));
  if (webLegalLanguages.includes(language)) write(`web/src/data/legal-locales/${language}.json`, json(bundle));
}
write('src/features/legal/locales.generated.ts',
  '// Generated by scripts/sync-legal-documents.mjs. Do not edit.\n'
  + 'import type { LegalBundle } from "./types";\n'
  + 'export const legalBundleLoaders: Record<string, () => LegalBundle> = {\n'
  + legalLanguages.map(language => `  ${JSON.stringify(language)}: () => require("./locales/${language}.json"),`).join('\n')
  + '\n};\n');
write('web/src/data/legal-locales.generated.ts',
  '// Generated by scripts/sync-legal-documents.mjs. Do not edit.\n'
  + 'import type { LegalBundle } from "../../../src/features/legal/types";\n'
  + 'export const legalBundleLoaders: Record<string, () => Promise<LegalBundle>> = {\n'
  + webLegalLanguages.map(language => `  ${JSON.stringify(language)}: () => import("./legal-locales/${language}.json").then(module => module.default as LegalBundle),`).join('\n')
  + '\n};\n');
write('web/src/data/legal-copy.generated.json', json(Object.fromEntries(
  webLegalLanguages.map(language => [language, bundles[language].copy]),
)));
console.log(`Synced four complete legal documents across ${legalLanguages.length} App languages and ${webLegalLanguages.length} Web languages.`);
